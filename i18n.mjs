export const LANGUAGES = Object.freeze(['en', 'zh-Hans', 'zh-Hant', 'es', 'fr', 'ja']);
export const STORAGE_KEY = 'md-studio-language';
let language = 'en';
const listeners = new Set();
export const getLanguage = () => language;
export function t(key, params = {}) {
  const template = messages[language][key];
  if (template === undefined) throw new Error('Missing locale key: ' + key);
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name + 'Key'] ? t(params[name + 'Key']) : params[name] ?? '{' + name + '}'));
}
// Retain the message key, not a translated snapshot: an existing error can change language.
export function localeError(key, params = {}) {
  const error = new Error();
  error.localeKey = key;
  error.localeParams = params;
  Object.defineProperty(error, 'message', {get: () => t(key, params), configurable: true});
  return error;
}
export function errorText(error) {
  if (error?.localeKey) return t(error.localeKey, error.localeParams);
  // Browser/native exception wording is not stable or localized to our selector.
  return t(error instanceof SyntaxError ? 'invalidJson' : 'operationFailed');
}
const sourceKeys = new Map(Object.entries(messages.en).map(([key, text]) => [text, key]));
let textBindings = [], attributeBindings = [];
export function bindUI(doc = document) {
  textBindings = []; attributeBindings = [];
  const walker = doc.createTreeWalker(doc.documentElement, 4);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement.closest('script,style,#language,[data-i18n]')) continue;
    const value = node.nodeValue, trimmed = value.trim(), key = sourceKeys.get(trimmed);
    if (key) textBindings.push({node, key, before: value.slice(0, value.indexOf(trimmed)), after: value.slice(value.indexOf(trimmed) + trimmed.length)});
  }
  for (const node of doc.querySelectorAll('[data-i18n]')) {
    const key = node.dataset.i18n;
    if (!Object.hasOwn(messages.en, key)) throw new Error('Missing explicit locale key: ' + key);
    textBindings.push({node: node.firstChild, key, before: '', after: ''});
  }
  for (const node of doc.querySelectorAll('[aria-label],[title],[placeholder],meta[name="description"]')) {
    for (const attr of ['aria-label','title','placeholder','content']) {
      const key = sourceKeys.get(node.getAttribute(attr));
      if (key) attributeBindings.push({node, key, attr});
    }
  }
}
export function applyUI(doc = document) {
  doc.documentElement.lang = language;
  for (const {node, key, before, after} of textBindings) if (node.isConnected) node.nodeValue = before + t(key) + after;
  for (const {node, key, attr} of attributeBindings) if (node.isConnected) node.setAttribute(attr, t(key));
  const selector = doc.getElementById('language');
  if (selector) selector.value = language;
}
export const uiBindings = () => ({texts: textBindings.filter(b=>b.node.isConnected), attributes: attributeBindings.filter(b=>b.node.isConnected)});
export function setLanguage(value, {persist = true} = {}) {
  language = LANGUAGES.includes(value) ? value : 'en';
  if (typeof document !== 'undefined') applyUI();
  if (persist) {try {globalThis.localStorage?.setItem(STORAGE_KEY, language);} catch {/* Getter and methods may deny storage: keep session language and notify listeners. */}}
  for (const listener of listeners) listener(language);
  return language;
}
export function onLanguageChange(listener) {listeners.add(listener);return () => listeners.delete(listener);}
export function initI18n(doc = document) {
  bindUI(doc);
  let saved;try {saved = localStorage.getItem(STORAGE_KEY);} catch {/* Default English without storage. */}
  setLanguage(saved, {persist: false});
  doc.getElementById('language')?.addEventListener('change', event => setLanguage(event.target.value));
}

